function [runStart, runEnd] = longest_true_run(mask)
    mask = logical(mask(:));
    edges = diff([false; mask; false]);
    starts = find(edges == 1);
    ends = find(edges == -1)-1;
    if isempty(starts)
        runStart = [];
        runEnd = [];
        return;
    end
    [~, best] = max(ends-starts+1);
    runStart = starts(best);
    runEnd = ends(best);
end

